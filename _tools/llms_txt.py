def read(rel: str) -> str:
    return (SITE / rel.strip("/") / "index.html").read_text() if rel != "/" else (SITE / "index.html").read_text()


def one(rx: str, text: str, what: str) -> str:
    m = re.search(rx, text, re.S)
    if not m:
        raise SystemExit(f"llms_txt: could not read {what} — its source moved; fix the pattern, never type the fact")
    return m.group(1)


def money(d: Decimal) -> str:
    return f"${d:.2f}".replace(".00", "") if d == d.to_integral() else f"${d:.2f}"


#: WHICH FREE EXPORTS ARE CAPPED (CEO decision 2026-10-13; the engine's list is freetier.CAPPED_TASKS, tests/test_the_site_states_the_free_export_cap.py
#: holds the two together): the AI enhancement work Pro is sold for stops at the cap; every utility tool (Convert, Mute, Compress, Loop,
#: Rotate, Split, GIF ...) runs its full length, still with the mark. ONE sentence, read by the product box, the pricing and download
#: pages, the new-page template and llms.txt, so no page can claim the cap covers a tool it does not.
CAPPED_LANES = "upscaling, restoring and colour exports"


def free_tier(cap: int, open_q: str = "“", close_q: str = "”") -> str:
    return (f"{CAPPED_LANES} up to {cap} seconds, everything else at full length, "
            f"video and GIF exports with a small {open_q}Made with Crisp{close_q} mark")


def offer_last_day(f: dict) -> str:
    """The offer's last day where it ends latest in the US (Pacific): FOUNDINGCRISP ends 2026-12-01T07:59:59Z, the last second
    of 30 November in California. Said as "through November" when that is a month's last day, else "until 30 November". Read
    from data-ends, never typed; anywhere east of California the offer in fact runs a few hours longer, never shorter."""
    import datetime as _dt
    from zoneinfo import ZoneInfo
    end = _dt.datetime.fromisoformat(f["ends"].replace("Z", "+00:00")).astimezone(ZoneInfo("America/Los_Angeles"))
    last = (end - _dt.timedelta(seconds=1)).date() if (end.hour, end.minute) == (0, 0) else end.date()
    if (last + _dt.timedelta(days=1)).day == 1:
        return f"through {last.strftime('%B')}"
    return f"until {last.day} {last.strftime('%B')}"


def offer_who(f: dict) -> str:
    """Who gets the founding price, in the one phrase every generator uses: the cap while there is one, else everyone and when."""
    return f"for the first {f['first']} buyers" if f["first"] else f"for everyone {offer_last_day(f)}"


def founding_live(f: dict, when=None) -> bool:
    """True until the founding offer's end (the mount's data-ends, UTC). A generator run after it writes no founding line."""
    import datetime as _dt
    end = _dt.datetime.fromisoformat(f["ends"].replace("Z", "+00:00"))
    return (when or _dt.datetime.now(_dt.timezone.utc)) < end


def speed_note(os_line: str, link: bool = True) -> str:
    """The plain note a box adds while the declared floor is below macOS 15: there Crisp upscales with ncnn, not Core ML
    (its Core ML models need macOS 15), so an upscale takes about 1.5 times as long (measured on an M1 Ultra, 10-19).
    Read from the floor, never typed: a floor of 15 or later returns nothing."""
    m = re.search(r"macOS\s+(\d+)", os_line or "")
    if not m or int(m.group(1)) >= 15:
        return ""
    text = f"slower upscaling on macOS {m.group(1)}"
    return f' (<a href="/download/#macos-speed">{text}</a>)' if link else f" ({text})"


def facts() -> dict:
    home = read("/")
    # `PRICE_USD = 129` or, since the 2026-11-02 halving, `PRICE_USD = Decimal("64.50")`: the engine's own exact figure either way
    price = Decimal(one(r"(?m)^PRICE_USD\s*=\s*(?:Decimal\([\"'])?(\d+(?:\.\d+)?)[\"']?\)?\s*$", ENGINE.read_text(), "PRICE_USD"))
    mount = one(r"(<div data-founding[^>]*>)", home, "the founding mount")
    f = {
        "price": price,
        # THE PRICE AFTER THE OFFER (2026-11-02): data-then, said as a future price ("then $29"). The struck-through data-was is
        # gone: Crisp has never charged $29, and "50% off" a price nobody has paid is not a saving (CEO: no "% off" against an
        # uncharged price). An older mount's data-was is still read, so a revert cannot silently drop the full-price check.
        "then": Decimal(one(r'data-(?:then|was)="\$([\d.]+)"', mount, "data-then")),
        "now": Decimal(one(r'data-now="\$([\d.]+)"', mount, "data-now")),
        "code": one(r'data-code="([A-Z0-9]+)"', mount, "data-code"),
        # A capped offer names its cap (data-first); since 2026-11-02 FOUNDINGCRISP is for everyone, so there is none.
        "first": int(m.group(1)) if (m := re.search(r'data-first="(\d+)"', mount)) else None,
        # When FOUNDINGCRISP expires in Dodo (CEO, 2026-10-21). The generators drop every founding line from then on.
        "ends": one(r'data-ends="([0-9T:\-]+Z)"', mount, "data-ends"),
        "bnpl": one(r"var\s+CRISP_BNPL_LIVE\s*=\s*(true|false)\s*;", home, "CRISP_BNPL_LIVE") == "true",
        # THE MAC'S FLOOR AND CHIP, from the lines that since 2026-11-05 also name Windows: "macOS 14.0 or later, Windows 10 or 11
        # (64-bit)" and "Apple Silicon (M1 or later) on a Mac". Every box, the download page and the speed note were written for the
        # Mac's part alone ("Download Crisp Video for Mac: <os>, <chip>"), so they get exactly that; Windows has its own line (WIN_REQ).
        "os": one(r'"operatingSystem":\s*"[^"]*?(macOS\s+[\d.]+\s+or later)', home, "operatingSystem (its macOS part)"),
        "chip": re.sub(r"\s+on a Mac$", "", one(r'"processorRequirements":\s*"([^"]+)"', home, "processorRequirements")),
        # The free-tier export cap, read from the engine like the price (entitlement.FREE_EXPORT_CAP_SECONDS): the site cannot drift from it.
        "cap": int(one(r"(?m)^FREE_EXPORT_CAP_SECONDS\s*=\s*(\d+)", ENGINE.read_text(), "FREE_EXPORT_CAP_SECONDS")),
        "macs": int(one(r"up to (?:<strong>)?(\d+) (?:Macs|computers) at a time", read("/legal/terms/"), "seats per licence")),
        "refund_days": int(one(r"within (\d+) days of purchase", read("/legal/refunds/"), "refund window")),
        "version": json.loads((SITE / "latest.json").read_text())["version"],
        "dmg": dmg_target(one(r'data-track="hero" href="([^"]+Crisp\.dmg)"', home, "the download link")),
        # The homepage now writes it as a sentence ("Pay once. Every 1.x update is included."); llms.txt keeps
        # its clause form, read from the page either way.
        "updates": one(r"([Ee]very \d+\.x update (?:is )?included)", home, "the update promise")
                   .replace(" is included", " included").replace("Every", "every", 1),
    }
    if f["then"] != price:
        raise SystemExit(f"llms_txt: the founding bar's full price {f['then']} is not PRICE_USD {price}")
    if f["bnpl"]:
        note = one(r'<p class="bnpl-note" data-crisp-bnpl>(.*?)</p>', home, "the instalment note")
        f["bnpl_providers"] = "Klarna or Afterpay" if "Klarna or Afterpay" in note else one(r"with (\w+ or \w+)", note, "providers")
        f["bnpl_where"] = "in the US" if "in the US" in note else ""
    return f


#: The hub's counting download route (CEO, 2026-09-28): counts people, not robots, stores no IP or user agent,
#: then 302s to the file. It accepts crisp-site release URLs only; `to=` stays LAST and UNENCODED so the href
#: still ends in Crisp.dmg — track.js's Plausible "Download" event and verify_ship.sh both key on that.
DL_BASE = "https://kerr-affiliate-hub.kerrco.workers.dev/dl/crisp"
DMG = "https://github.com/mattkerr09/crisp-site/releases/download/v1/Crisp.dmg"


def dmg_target(href: str) -> str:
    """The file a download link serves: the href itself, or a hub link's `to=`."""
    m = re.search(r"[?&]to=(https://[^&]+Crisp\.dmg)$", href)
    return m.group(1) if m else href


def dl_url(src: str) -> str:
    return f"{DL_BASE}?src={src}&to={DMG}"


#: WINDOWS 10 OR 11, 64-BIT (CEO, 2026-11-03: the signed Windows build is live). Read from the Windows updater's own manifest,
#: which scripts/windows_release.py writes with the version and the VERSIONED, immutable installer it published, so a link
#: here can never name an installer that was not published. None until a Windows release exists.
WIN_REQ = "Windows 10 or 11, 64-bit"
#: AND THE GRAPHICS (CEO, 2026-11-05). The upscaler is ncnn on Vulkan and there is no CPU path (upscale.py passes no -g -1; the app stops
#: with errors.NO_VULKAN_ON_THIS_PC when the driver offers none), so on Windows upscaling needs graphics that support Vulkan. Hardware: NVIDIA
#: Kepler (2012) and newer, AMD GCN (2012) and newer, Intel Haswell/Skylake (2013 to 2015) and newer; Steam's survey put DirectX 12 GPUs, the
#: same generations, at 94.14% of systems in February 2026. "Most PCs from 2016 on" is the claim that holds, and it is all this says.
WIN_GPU = "graphics that support Vulkan"
WIN_GPU_NOTE = "most PCs from 2016 on have them"


def windows() -> "dict | None":
    try:
        m = json.loads((SITE / "updater-windows.json").read_text())
        url = m["platforms"]["windows-x86_64"]["url"]
    except (OSError, ValueError, KeyError, TypeError):
        return None
    if not re.fullmatch(r"https://github\.com/mattkerr09/crisp-site/releases/download/v1/Crisp-[\d.]+-x64-setup\.exe", url):
        return None
    return {"version": m["version"], "url": url}


def dl_win_url(src: str) -> str:
    w = windows()
    return f"{DL_BASE}?src={src}&to={w['url']}" if w else ""


