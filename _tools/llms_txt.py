def offer_last_day(f: dict) -> str:
    """The offer's last day where it ends latest in the US (Pacific): FOUNDINGCRISP ends 2026-12-03T07:59:59Z, the last second
    of 2 December in California. The copy names both the month and day. Read
    from data-ends, never typed; anywhere east of California the offer in fact runs a few hours longer, never shorter."""
    import datetime as _dt
    from zoneinfo import ZoneInfo
    end = _dt.datetime.fromisoformat(f["ends"].replace("Z", "+00:00")).astimezone(ZoneInfo("America/Los_Angeles"))
    last = (end - _dt.timedelta(seconds=1)).date() if (end.hour, end.minute) == (0, 0) else end.date()
    return f"through {last.strftime('%B')} {last.day}"


def future_day(f: dict) -> str:
    import datetime as _dt
    from zoneinfo import ZoneInfo
    end = _dt.datetime.fromisoformat(f["ends"].replace("Z", "+00:00")).astimezone(ZoneInfo("America/Los_Angeles"))
    day = (end + _dt.timedelta(seconds=1)).date()
    return f"{day.strftime('%B')} {day.day}"


def price_copy(f: dict) -> str:
    if not founding_live(f):
        return f"{money(f['price'])} once."
    return sale_copy(f)


def sale_copy(f: dict) -> str:
    """The dated sale record, also checked after expiry when the mount is hidden."""
    return (f"Black Friday sale: {money(f['now'])} once, {f['percent']}% off our November price of "
            f"{money(f['november'])}, {offer_last_day(f)}. Then {money(f['price'])}.")


def price_short(f: dict) -> str:
    """The sale for metadata, where about 165 characters is all a result shows: price, last day and the price after. The
    percent is only ever said as the full "our November price" sentence (sale_copy), on the page itself."""
    if not founding_live(f):
        return f"{money(f['price'])} once."
    return f"Black Friday sale: {money(f['now'])} once {offer_last_day(f)}, then {money(f['price'])}."


def price_markup(f: dict) -> str:
    copy = price_copy(f)
    if not founding_live(f):
        return copy
    product = f' data-product="{f["product"]}"' if "product" in f else ""
    return (f'<span data-launch-price data-price-ends="{f["ends"]}"{product} '
            f'data-full-price="{money(f["price"])} once.">{copy}</span>')


def pro_offers(f: dict) -> list[dict]:
    import datetime as dt
    from zoneinfo import ZoneInfo
    end = dt.datetime.fromisoformat(f['ends'].replace('Z', '+00:00')).astimezone(ZoneInfo('America/Los_Angeles'))
    regular = {"@type": "Offer", "name": "Pro", "price": f'{f["price"]:.2f}', "priceCurrency": "USD",
               "validFrom": (end + dt.timedelta(seconds=1)).date().isoformat()}
    if not founding_live(f):
        return [regular]
    sale = {"@type": "Offer", "name": "Pro", "price": f'{f["now"]:.2f}', "priceCurrency": "USD",
            "priceValidUntil": end.date().isoformat()}
    return [sale, regular]


