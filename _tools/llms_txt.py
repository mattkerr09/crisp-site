"""Build /llms.txt (llmstxt.org format) from the facts the site and the engine already state.

CEO order, 2026-09-26 (Matthew: "AI-search visibility fixes, all site-side"): an llms.txt at the root in the
format outlier.host uses — H1, one-line summary blockquote, then "## " sections of "- [Title](url): note" —
pointing an AI at the pages it should cite, with every claim from the factbase and generated by the build.

NOTHING HERE IS TYPED TWICE. Each fact is read from the file that already has to be true:
  price ............ ../backend/crisp_engine/entitlement.py PRICE_USD (the app's own till; the site gates agree)
  founding offer ... index.html's founding mount (data-was / data-now / data-code / data-first)
  pay in four ...... index.html's CRISP_BNPL_LIVE flag and its instalment note — omitted entirely while dark
  macOS / chip ..... index.html's JSON-LD operatingSystem / processorRequirements
  Macs per licence . legal/terms "up to N Macs at a time"
  refund window .... legal/refunds "within N days of purchase"
  version .......... latest.json
  page titles/notes  each page's own <title> and meta description
tests/test_llms_txt_is_the_generated_one.py fails the push when llms.txt differs from what this prints, so a
price or a page title that moves makes the file regenerate, not drift.

WHICH PAGES. Search Console could not rank the how-to guides (read 2026-09-28: one how-to with any data in
90 days — 2 impressions), so HOWTOS is a stated editorial list: the guides for Crisp's core job (restore,
upscale, denoise, stabilise), the one Search Console has seen first. Never a page that canonicalises
elsewhere, and never an arm of a running experiment (~/ops/search/ARMS.md) — a new inbound link is a change.

    python3 _tools/llms_txt.py           # write llms.txt
    python3 _tools/llms_txt.py --print   # print it
"""
