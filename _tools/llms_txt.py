def quarter(d: Decimal) -> Decimal:
    return (d / 4).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


#: PAY IN FOUR HAS A FLOOR (2026-11-02, prices halved). Dodo shows Klarna / Afterpay only on a payment above $50.01, so the
#: $64.50 price has it and the $32.25 founding price does not. Every generator asks this one question before it prints a split.
BNPL_FLOOR = Decimal("50.01")


def bnpl_on(f: dict, amount: Decimal) -> bool:
    return bool(f["bnpl"]) and Decimal(amount) > BNPL_FLOOR


def page_meta(rel: str) -> tuple[str, str]:
    s = read(rel)
    canon = one(r'<link rel="canonical" href="([^"]+)"', s, f"{rel} canonical")
    if canon != BASE + rel:
        raise SystemExit(f"llms_txt: {rel} canonicalises to {canon} — link the canonical page instead")
    title = html.unescape(one(r"<title>(.*?)</title>", s, f"{rel} title"))
    title = re.sub(r"\s*[—|]\s*Crisp(?: Video)?\s*$", "", title).strip()
    desc = html.unescape(one(r'<meta name="description" content="([^"]*)"', s, f"{rel} description"))
    sentences = re.split(r"(?<=[.!?])\s+", desc)
    first = sentences[0]
    if "Black Friday sale:" in first and len(sentences) > 1 and sentences[1].startswith("Then "):
        first += " " + sentences[1]
    return title, first


def link(rel: str, note: str | None = None) -> str:
    title, first = page_meta(rel)
    return f"- [{title}]({BASE}{rel}): {note or first}"


