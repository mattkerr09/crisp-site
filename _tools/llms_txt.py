def read(rel: str) -> str:
    return (SITE / rel.strip("/") / "index.html").read_text() if rel != "/" else (SITE / "index.html").read_text()


def one(rx: str, text: str, what: str) -> str:
    m = re.search(rx, text, re.S)
    if not m:
        raise SystemExit(f"llms_txt: could not read {what} — its source moved; fix the pattern, never type the fact")
    return m.group(1)


def money(d: Decimal) -> str:
    return f"${d:.2f}".replace(".00", "") if d == d.to_integral() else f"${d:.2f}"


def engine_amount(engine: str, name: str) -> Decimal:
    return Decimal(one(rf"(?m)^{name}\s*=\s*(?:Decimal\([\"'])?(\d+(?:\.\d+)?)[\"']?\)?[ \t]*(?:#[^\n]*)?$",
                       engine, name))


