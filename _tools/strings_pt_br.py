def money(amount) -> str:
    value = f"{amount:.2f}".replace(".", ",")
    return "US$ " + (value[:-3] if value.endswith(",00") else value)


def fact(text: str) -> str:
    return text.replace(" or later", " ou posterior").replace("(", "").replace(")", "")


