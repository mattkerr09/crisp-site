"""No internal notes in what the site ships.

GitHub Pages serves this repo as it is, so every comment is public: view-source shows old prices, rival names, file paths
and who decided what. The CEO's QC found "One-time $64.50" in the home page's inline CSS (2026-11-08), and the inline
checkout script still carried "$129.00 $64.50" after the HTML and CSS pass. So this covers HTML, CSS and JavaScript:
inline <style> and <script> blocks and the shipped .css and .js files.

Allowed, because something reads them:
  <!-- name:begin -->, <!-- name:end -->, <!-- name:begin (written by _tools/x.py) -->   tools find their regions
  <!-- Generated by _tools/x.py. Edit that, not this file. -->                            points at the generator
  // upstream-reviewed: <sha256>                                                           ~/ops/bin/drift.py (founding.js)
  /* name:begin */, /* name:end */  in JavaScript                                           tests slice code at them
Everything else is an internal note: --write removes it, --check (the pre-push gate) fails on it.

JavaScript is read with a small tokenizer (strings, template literals, regular expressions), not a regex, because "//"
also starts every URL in a string. --check also runs `node --check` on every script it would change, so a tokenizer
mistake fails the gate instead of shipping broken code.

Rationale that used to live in those comments is in git history. Write new rationale in the generator or the commit.

    python3 _tools/shipped_comments.py --check
    python3 _tools/shipped_comments.py --write
    python3 _tools/shipped_comments.py --selftest
"""
from __future__ import annotations

import difflib
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

SITE = Path(__file__).resolve().parents[1]

HTML_COMMENT = re.compile(r"<!--(.*?)-->", re.S)
CSS_COMMENT = re.compile(r"/\*.*?\*/", re.S)
HTML_TOKEN = re.compile(r"<!--(?P<comment>.*?)-->"
                        r"|(?P<open><(?P<tag>script|style)\b(?P<attrs>[^>]*)>)(?P<body>.*?)(?P<close></(?P=tag)>)", re.S | re.I)
ALLOWED = re.compile(r"\s*(?:[a-z0-9-]+:(?:begin|end)(?: \(written by _tools/[a-z0-9_]+\.py\))?"
                     r"|Generated by _tools/[a-z0-9_]+\.py\. Edit (?:that|the generator), not this (?:file|page)\.)\s*")
JS_ALLOWED = re.compile(r"//\s*upstream-reviewed:\s*[0-9a-f]{64}\s*")

# after these, a "/" starts a regular expression rather than dividing
_REGEX_AFTER_WORDS = {"return", "typeof", "case", "do", "else", "in", "of", "new", "delete", "void", "throw",
                      "instanceof", "yield", "await"}
_REGEX_AFTER_CHARS = set("(,=:[!&|?{};+-*%<>~^")


def shipped() -> list[Path]:
    out = []
    for p in sorted(list(SITE.rglob("*.html")) + list(SITE.rglob("*.css")) + list(SITE.rglob("*.js"))):
        rel = p.relative_to(SITE)
        if any(part.startswith(("_", ".")) for part in rel.parts) or "node_modules" in rel.parts:
            continue
        out.append(p)
    return out


def _strip_css(css: str) -> tuple[str, list[str]]:
    found = [m.group(0) for m in CSS_COMMENT.finditer(css)]
    return CSS_COMMENT.sub("", css), found


def strip_js(src: str) -> tuple[str, list[str]]:
    """(src without its comments, the comments). Strings, template literals and regular expressions are copied as they are."""
    out: list[str] = []
    found: list[str] = []
    i, n = 0, len(src)
    last = ""            # the last significant token: a punctuator char, or a word
    depth: list[int] = []  # brace depth at each open ${ inside a template literal

    def template(i: int) -> int:
        """Copy a template literal from its opening backtick; returns the index after it. ${...} returns to code."""
        out.append(src[i]); i += 1
        while i < n:
            c = src[i]
            if c == "\\":
                out.append(src[i:i + 2]); i += 2
            elif c == "`":
                out.append(c); return i + 1
            elif src.startswith("${", i):
                out.append("${"); depth.append(0); return i + 2
            else:
                out.append(c); i += 1
        return i

    while i < n:
        c = src[i]
        if c in "'\"":
            j = i + 1
            while j < n and src[j] != c:
                j += 2 if src[j] == "\\" else 1
            out.append(src[i:j + 1]); i = j + 1; last = "str"
        elif c == "`":
            i = template(i); last = "str"
        elif depth and c == "}" and depth[-1] == 0:
            depth.pop(); out.append("}"); i += 1
            # back inside the template literal
            while i < n:
                d = src[i]
                if d == "\\":
                    out.append(src[i:i + 2]); i += 2
                elif d == "`":
                    out.append(d); i += 1; break
                elif src.startswith("${", i):
                    out.append("${"); depth.append(0); i += 2; break
                else:
                    out.append(d); i += 1
            last = "str"
        elif src.startswith("//", i):
            j = src.find("\n", i)
            j = n if j < 0 else j
            text = src[i:j]
            if JS_ALLOWED.fullmatch(text):
                out.append(text)
            else:
                found.append(text)
            i = j
        elif src.startswith("/*", i):
            j = src.find("*/", i + 2)
            j = n if j < 0 else j + 2
            marker = re.match(r"/\*\s*([a-z0-9-]+:(?:begin|end))\b", src[i:j])
            if marker:            # a region marker: tests and tools slice the code at it; any note after it goes
                bare = f"/* {marker.group(1)} */"
                if src[i:j] != bare:
                    found.append(src[i:j])
                out.append(bare)
                i = j
                continue
            found.append(src[i:j])
            keep = re.search(r"upstream-reviewed:\s*([0-9a-f]{64})", src[i:j])
            if keep:              # drift.py reads this one line; the note around it goes
                out.append(f"// upstream-reviewed: {keep.group(1)}")
                i = j
                continue
            before = out[-1][-1:] if out and out[-1] else ""
            after = src[j:j + 1]
            if before and after and not before.isspace() and not after.isspace():
                out.append(" ")       # a/**/b must not become ab
            i = j
        elif c == "/" and (last == "" or last in _REGEX_AFTER_CHARS or last in _REGEX_AFTER_WORDS):
            j, in_class = i + 1, False
            while j < n and src[j] != "\n":
                d = src[j]
                if d == "\\":
                    j += 2; continue
                if d == "[":
                    in_class = True
                elif d == "]":
                    in_class = False
                elif d == "/" and not in_class:
                    break
                j += 1
            j += 1
            while j < n and (src[j].isalnum() or src[j] == "_"):
                j += 1   # flags
            out.append(src[i:j]); i = j; last = "re"
        elif c.isalnum() or c in "_$":
            j = i
            while j < n and (src[j].isalnum() or src[j] in "_$"):
                j += 1
            out.append(src[i:j]); last = src[i:j]; i = j
        else:
            if depth and c == "{":
                depth[-1] += 1
            elif depth and c == "}":
                depth[-1] -= 1
            out.append(c)
            if not c.isspace():
                last = c if c not in ")]" else "close"
            i += 1
    return "".join(out), found


def clean(text: str, kind: str) -> tuple[str, list[str]]:
    """(text without internal notes, the notes removed). kind is html, css or js."""
    if kind == "css":
        return _strip_css(text)
    if kind == "js":
        return strip_js(text)
    found: list[str] = []
    pieces, pos = [], 0
    # One pass in document order: a comment that MENTIONS "<style>" is still a comment, and a "<!--" inside a script is
    # still script (the home page's font note said "the inline <style> below" and hid from the first version, 2026-11-08).
    for m in HTML_TOKEN.finditer(text):
        pieces.append(text[pos:m.start()])
        if m.group("comment") is not None:
            if ALLOWED.fullmatch(m.group("comment")):
                pieces.append(m.group(0))
            else:
                found.append(m.group(0))
        else:
            body = m.group("body")
            if m.group("tag").lower() == "style":
                body, more = _strip_css(body)
                found += more
            elif "ld+json" not in m.group("attrs") and "application/json" not in m.group("attrs"):
                body, more = strip_js(body)
                found += more
            pieces.append(m.group("open") + body + m.group("close"))
        pos = m.end()
    pieces.append(text[pos:])
    return "".join(pieces), found


def clean_lines(src: str, kind: str) -> tuple[str, list[str]]:
    """clean(), then remove only the lines a removed comment left blank (lines that were blank before stay)."""
    out, found = clean(src, kind)
    if not found:
        return src, found
    before = src.splitlines(keepends=True)
    after = out.splitlines(keepends=True)
    result = []
    sm = difflib.SequenceMatcher(a=before, b=after, autojunk=False)
    for tag, _i1, _i2, j1, j2 in sm.get_opcodes():
        if tag == "equal":
            result += after[j1:j2]
        else:
            result += [line for line in after[j1:j2] if line.strip()]
    return "".join(result), found


def kind_of(p: Path) -> str:
    return {".css": "css", ".js": "js"}.get(p.suffix, "html")


def scripts_of(text: str, kind: str) -> list[str]:
    if kind == "js":
        return [text]
    if kind == "css":
        return []
    return [m.group("body") for m in HTML_TOKEN.finditer(text)
            if m.group("comment") is None and m.group("tag").lower() == "script"
            and "ld+json" not in m.group("attrs") and "application/json" not in m.group("attrs") and m.group("body").strip()]


def node_check(scripts: list[str]) -> list[str]:
    """Each script that node will not parse, with node's reason. Empty when node is missing (the caller blocks on that)."""
    bad = []
    with tempfile.TemporaryDirectory(prefix="shipped-comments-") as d:
        for k, code in enumerate(scripts):
            f = Path(d) / f"s{k}.js"
            f.write_text(code, encoding="utf-8")
            r = subprocess.run(["node", "--check", str(f)], capture_output=True, text=True)
            if r.returncode:
                bad.append((r.stderr.strip().splitlines() or ["?"])[-1])
    return bad


def run(write: bool) -> int:
    if not shutil.which("node"):
        print("BLOCKED: node is not on PATH, so a stripped script cannot be proven to parse")
        return 1
    bad, broken = {}, []
    for p in shipped():
        src = p.read_text(encoding="utf-8")
        kind = kind_of(p)
        out, found = clean_lines(src, kind)
        if not found:
            continue
        rel = str(p.relative_to(SITE))
        bad[rel] = found
        was_ok = not node_check(scripts_of(src, kind))
        errors = node_check(scripts_of(out, kind)) if was_ok else []
        if errors:
            broken.append(f"{rel}: {errors[0]}")
        elif write:
            p.write_text(out, encoding="utf-8")
    total = sum(len(v) for v in bad.values())
    if broken:
        print("FAIL: removing comments would break these scripts (fix the tokenizer, do not ship):")
        print("\n".join("  " + b for b in broken))
        return 1
    if write:
        print(f"shipped comments: removed {total} internal notes from {len(bad)} files; every changed script parses")
        return 0
    if bad:
        print(f"FAIL: {total} internal notes in {len(bad)} shipped files (run _tools/shipped_comments.py --write):")
        for rel, found in list(bad.items())[:8]:
            print(f"  {rel}: {found[0][:90]!r}" + (f" (+{len(found) - 1} more)" if len(found) > 1 else ""))
        return 1
    print(f"OK: no internal notes in {len(shipped())} shipped HTML, CSS and JavaScript files")
    return 0


def selftest() -> int:
    sha = "7c188606ec8456cf7631c944fd1cc5112796ab55b68384c547b7b91555122528"
    cases = [
        ("<p>a</p><!-- One-time $64.50 -->\n", "html", "<p>a</p>\n", 1),
        ("<!-- xsell:begin (written by _tools/thankyou_xsell.py) --><p>x</p><!-- xsell:end -->", "html", None, 0),
        ("<!-- de-box:begin --><aside></aside><!-- de-box:end -->", "html", None, 0),
        ("<!-- Generated by _tools/landing_pages.py. Edit that, not this file. -->", "html", None, 0),
        ("<!-- Generated by _tools/landing_pages.py — a door for /x/, noindex -->", "html", "", 1),
        ("<style>a{color:red}/* Linear ships rgb(8,9,10) */</style>", "html", "<style>a{color:red}</style>", 1),
        ("a{b:c}\n/* THE TRUST ROW SAT FLUSH */\nd{e:f}\n", "css", "a{b:c}\nd{e:f}\n", 1),
        ("<div>\n  <!-- note\n       two lines -->\n  <p>k</p>\n\n</div>\n", "html", "<div>\n  <p>k</p>\n\n</div>\n", 1),
        # JavaScript: the inline checkout note that survived the first pass
        ("<script>\n/* measured: \"$129.00 $64.50\" */\nvar u = \"https://x.test/a\";\n</script>", "html",
         "<script>\nvar u = \"https://x.test/a\";\n</script>", 1),
        ("<script>var s='<!-- not a comment -->'; // note\n</script>", "html", "<script>var s='<!-- not a comment -->'; \n</script>", 1),
        ("var a = 'http://x//y', b = \"/*no*/\", c = `//${1 /* in */ + 2}//`;\n", "js",
         "var a = 'http://x//y', b = \"/*no*/\", c = `//${1  + 2}//`;\n", 1),
        ("var r = /\\/\\/[^/]*\\//g; // r\nvar d = a / b / c;\n", "js", "var r = /\\/\\/[^/]*\\//g; \nvar d = a / b / c;\n", 1),
        ("if (x) return /[/]*/.test(y); else z = 1;\n", "js", None, 0),
        ("a/**/b;\n", "js", "a b;\n", 1),
        (f"/*\n * upstream note\n */\n// upstream-reviewed: {sha}\n(function(){{}})();\n", "js",
         f"// upstream-reviewed: {sha}\n(function(){{}})();\n", 1),
        ('<script type="application/ld+json">{"u":"https://x.test//a"}</script>', "html", None, 0),
        ("<head>\n<!-- The two faces. They are declared in the inline <style> below -->\n<style>a{b:c}</style>\n</head>", "html",
         "<head>\n<style>a{b:c}</style>\n</head>", 1),
        ("/* send-mac-link:begin */\nf();\n/* send-mac-link:end */\n", "js", None, 0),
        ("/* send-mac-link:begin. THE SAME BLOCK is inline at the foot of index.html */\nf();\n", "js",
         "/* send-mac-link:begin */\nf();\n", 1),
        (f"/*\n * the fork's story\n * upstream-reviewed: {sha}  (2026-10-05, a note)\n */\n(function(){{}})();\n", "js",
         f"// upstream-reviewed: {sha}\n(function(){{}})();\n", 1),
    ]
    for src, kind, want, n in cases:
        out, found = clean_lines(src, kind)
        if len(found) != n or (want is not None and out != want) or (want is None and out != src):
            print(f"FAIL: selftest {src[:60]!r} -> {out!r} ({len(found)} found, wanted {n})")
            return 1
    if shutil.which("node") and node_check(["var x = ;"]) == []:
        print("FAIL: selftest node --check accepted a broken script, so the parse proof proves nothing")
        return 1
    print(f"OK: {len(cases)} shipped-comment cases, and the parse proof rejects a broken script")
    return 0


if __name__ == "__main__":
    if "--selftest" in sys.argv:
        sys.exit(selftest())
    sys.exit(run("--write" in sys.argv))
